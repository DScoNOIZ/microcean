#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ЭКСПЕРИМЕНТ E1 (R2): Комбинаторная оценка пространства фрагментов +
численный пример схема-теоремы Холланда и дрейфа.
См. теоретическую часть концепции (R1), план E1.

Что считаем:
 1) log10 C(N_F, k) = log10(N_F!/(k!(N_F-k)!)) через math.lgamma
    (лог-факториалы; точного переполнения избегаем).
    Сетка: N_F in {10^2, 10^3, 10^4, 10^6}, k in {3,5,10,20}.
 2) Численный пример схема-теоремы Холланда:
    E[m(H,t+1)] ~= m(H,t) * r * [1 - p_c*d(H)/(L-1) - o(H)*p_m],  r = f_hat/f_bar.
    L=20. H1 короткая (d=2, o=2) vs H2 длинная (d=16, o=10).
 3) Дрейф: вероятность фиксации нейтрального аллеля ~ 1/N для N in {50,100,200}.
 4) Доля пространства, просматриваемая GA: N*G оценок vs |пространства|.

Версии: python 3.13, numpy не требуется (детерминированные формулы, seed не нужен).
"""
import math

def logC10(N, k):
    # log10 C(N,k); lgamma(n+1) = ln(n!)
    return (math.lgamma(N + 1) - math.lgamma(k + 1) - math.lgamma(N - k + 1)) / math.log(10)

def exactC(N, k):
    return math.comb(N, k)

def fmt(x):
    # компактная запись 10^y
    return f"10^{x:.2f}"

out = []
def line(s=""):
    out.append(s)

# ---------------------------------------------------------------- 1. таблица
line("=" * 78)
line("E1. ПРОСТРАНСТВО КОМБИНАЦИЙ: log10 C(N_F, k)")
line("=" * 78)
line(f"{'N_F':>10} | {'k=3':>14} | {'k=5':>14} | {'k=10':>14} | {'k=20':>14}")
line("-" * 78)
Ns = [10**2, 10**3, 10**4, 10**6]
ks = [3, 5, 10, 20]
for N in Ns:
    cells = []
    for k in ks:
        v = logC10(N, k)
        cells.append(fmt(v))
    line(f"{N:>10} | {cells[0]:>14} | {cells[1]:>14} | {cells[2]:>14} | {cells[3]:>14}")
# контроль точных значений для малых N
line("-" * 78)
line("Контроль (точные C(N,k) для малых N):")
line(f"  C(100,3)  = {exactC(100,3):,}  (log10 = {logC10(100,3):.4f})")
line(f"  C(100,5)  = {exactC(100,5):,}  (log10 = {logC10(100,5):.4f})")
line(f"  C(1000,10) = {exactC(1000,10)} (log10 = {logC10(1000,10):.4f})")

# ---------------------------------------------------------------- 2. схема-теорема
line("")
line("=" * 78)
line("E1.2 СХЕМА-ТЕОРЕМА ХОЛЛАНДА — численный пример (L=20, p_c=0.8)")
line("=" * 78)
line("Формула (нижняя оценка ожидания):")
line("  E[m(H,t+1)] ~= m(H,t) * r * [1 - p_c*d(H)/(L-1) - o(H)*p_m],  r=f_hat/f_bar")
line("")
L = 20
p_c = 0.8
schemas = [("H1 короткая (d=2,  o=2)",  2,  2),
           ("H2 длинная  (d=16, o=10)", 16, 10)]
scenarios = [("сценарий A: p_m=0.01, r=1.5", 0.01, 1.5),
             ("сценарий B: p_m=0.05, r=2.0  (параметры GA из E2)", 0.05, 2.0)]
for sname, p_m, r in scenarios:
    line(f"--- {sname} ---")
    line(f"{'схема':<28} | {'q (множитель)':>14} | {'m(0)':>6} | {'m(10)':>10} | {'m(25)':>12} | {'m(50)':>14}")
    for hname, d, o in schemas:
        q = r * (1.0 - p_c * d / (L - 1) - o * p_m)
        m0 = 1.0
        m10 = m0 * q**10
        m25 = m0 * q**25
        m50 = m0 * q**50
        line(f"{hname:<28} | {q:>14.4f} | {m0:>6.1f} | {m10:>10.4f} | {m25:>12.6f} | {m50:>14.8f}")
    line("")

# ---------------------------------------------------------------- 3. дрейф
line("=" * 78)
line("E1.3 ДРЕЙФ: вероятность фиксации нейтрального аллеля ~ 1/N")
line("=" * 78)
for N in (50, 100, 200):
    line(f"  N = {N:>4}: p_fix ~ 1/N = {1.0/N:.4f}")

# ---------------------------------------------------------------- 4. доля пространства
line("")
line("=" * 78)
line("E1.4 ДОЛЯ ПРОСТРАНСТВА, ПРОСМАТРИВАЕМАЯ GA")
line("=" * 78)
N_POP, G = 100, 200
evals = N_POP * G
line(f"  Бюджет оценок GA (E2): N={N_POP}, G={G}  =>  {evals:,} оценок.")
for NF, k in [(10**4, 10), (10**6, 20)]:
    size = logC10(NF, k)
    line(f"  Пространство C({NF},{k}) ~ 10^{size:.2f}; доля просмотра = "
         f"{evals}/10^{size:.2f} ~ 10^{math.log10(evals)-size:.2f}  "
         f"(т.е. GA видит < 10^{size-math.log10(evals):.2f} долю пространства).")

print("\n".join(out))
with open("results/EXP1_output.txt", "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")